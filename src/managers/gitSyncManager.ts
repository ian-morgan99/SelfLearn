import * as vscode from "vscode";
import * as path from "path";
import { execSync } from "child_process";
import { SecureStorageManager } from "./secureStorageManager";
import { GitHubAPIManager } from "./gitHubAPIManager";

export class GitSyncManager {
  private context: vscode.ExtensionContext;
  private enableGitHubSync: boolean = false;
  private autoCommit: boolean = true;
  private autoPush: boolean = false;
  private syncBranch: string = "main";
  private enablePrivateGitHubRepo: boolean = false;
  private gitHubRepoUrl: string = "";
  private customStorageLocation: string = "";
  private secureStorage: SecureStorageManager;
  private gitHubAPI: GitHubAPIManager;
  public lastError?: string;

  constructor(
    context: vscode.ExtensionContext,
    secureStorage: SecureStorageManager,
  ) {
    this.context = context;
    this.secureStorage = secureStorage;
    this.gitHubAPI = new GitHubAPIManager(secureStorage);
    this.updateConfig();
  }

  public updateConfig(): void {
    const config = vscode.workspace.getConfiguration("ai-learning-repo");
    this.enableGitHubSync = config.get("enableGitHubSync", false);
    this.autoCommit = config.get("gitHubAutoCommit", true);
    this.autoPush = config.get("gitHubAutoPush", false);
    this.syncBranch = config.get("gitHubSyncBranch", "main");
    this.enablePrivateGitHubRepo = config.get("enablePrivateGitHubRepo", false);
    this.gitHubRepoUrl = config.get("gitHubRepoUrl", "");
    this.customStorageLocation = config.get("customStorageLocation", "");
  }

  /**
   * Directory that acts as the git repository for learnings.
   * Learnings live in the extension's storage location (customStorageLocation when
   * set, otherwise globalStorageUri) - never in the currently open workspace.
   */
  public getLearningsRepoRoot(): string {
    if (this.customStorageLocation && this.customStorageLocation.trim()) {
      return path.resolve(this.customStorageLocation.trim());
    }

    const globalStorage = this.context.globalStorageUri?.fsPath;
    if (globalStorage) {
      return path.resolve(globalStorage);
    }

    return process.cwd();
  }

  /**
   * Files that must never be committed to the learnings repository.
   */
  private getLearningsGitignore(): string {
    return [
      "# Generated by AI Learning Repository",
      "# Local backups and scratch state are never pushed to GitHub",
      "*.backup-*",
      "*.bak",
      ".backup/",
      "backups/",
      ".vscode/",
      ".DS_Store",
      "Thumbs.db",
      "node_modules/",
      "",
    ].join("\n");
  }

  /**
   * Make sure the learnings storage folder is a git repository whose origin points
   * at gitHubRepoUrl. Safe to call repeatedly.
   */
  public async ensureRepository(
    repoRoot: string,
  ): Promise<{ ok: boolean; error?: string }> {
    try {
      if (!this.gitHubRepoUrl || !this.gitHubRepoUrl.trim()) {
        return {
          ok: false,
          error:
            "No GitHub repository configured. Set ai-learning-repo.gitHubRepoUrl in settings.",
        };
      }

      const token = await this.secureStorage.getGitHubToken();
      const cleanUrl = this.gitHubRepoUrl.trim().replace(/\/+$/, "");
      // Without a stored token we still configure a credential-free remote and let
      // git's credential helper (e.g. Git Credential Manager) authenticate pushes.
      const authUrl = token
        ? cleanUrl.replace(
            "https://github.com/",
            "https://x-access-token:" + token + "@github.com/",
          )
        : cleanUrl;

      if (!token) {
        console.log(
          "[GitSync] No stored GitHub token - falling back to the git credential helper for " +
            cleanUrl,
        );
      }

      if (!(await this.isGitRepository(repoRoot))) {
        execSync("git init -b main", { cwd: repoRoot, stdio: "pipe" });
        execSync('git config user.name "AI Learning Repository"', {
          cwd: repoRoot,
          stdio: "pipe",
        });
        execSync('git config user.email "ai-learning-repo@local"', {
          cwd: repoRoot,
          stdio: "pipe",
        });
        console.log("[GitSync] Initialized repository at " + repoRoot);
      }

      // Never push local backups.
      const gitignoreUri = vscode.Uri.file(path.join(repoRoot, ".gitignore"));
      try {
        await vscode.workspace.fs.stat(gitignoreUri);
      } catch {
        await vscode.workspace.fs.writeFile(
          gitignoreUri,
          new TextEncoder().encode(this.getLearningsGitignore()),
        );
      }

      let existingRemote = "";
      try {
        existingRemote = execSync("git remote get-url origin", {
          cwd: repoRoot,
          stdio: "pipe",
          encoding: "utf8",
        }).trim();
      } catch {
        existingRemote = "";
      }

      const stripCreds = (u: string) => u.replace(/\/\/[^@/]+@/, "//");
      if (!existingRemote) {
        execSync('git remote add origin "' + authUrl + '"', {
          cwd: repoRoot,
          stdio: "pipe",
        });
        console.log("[GitSync] Configured origin -> " + cleanUrl);
      } else if (stripCreds(existingRemote) !== stripCreds(authUrl)) {
        execSync('git remote set-url origin "' + authUrl + '"', {
          cwd: repoRoot,
          stdio: "pipe",
        });
        console.log("[GitSync] Updated origin -> " + cleanUrl);
      } else if (token && !existingRemote.includes("@github.com")) {
        // Remote already points at the right repo; refresh credentials only.
        execSync('git remote set-url origin "' + authUrl + '"', {
          cwd: repoRoot,
          stdio: "pipe",
        });
      }

      return { ok: true };
    } catch (error) {
      const message = this.describeGitError(error);
      console.warn("[GitSync] ensureRepository failed:", message);
      return { ok: false, error: message };
    }
  }

  /**
   * Pull execSync errors apart - the useful text lives in error.stderr.
   */
  private describeGitError(error: unknown): string {
    const anyErr = error as { stderr?: string | Buffer; message?: string };
    const rawStderr = anyErr?.stderr
      ? Buffer.isBuffer(anyErr.stderr)
        ? anyErr.stderr.toString("utf8")
        : String(anyErr.stderr)
      : "";
    const cleaned = (rawStderr.trim() || anyErr?.message || String(error))
      .replace(/\/\/[^@/]+@/g, "//***@")
      .split("\n")
      .filter((l) => l.trim())
      .slice(-2)
      .join(" ");
    return cleaned;
  }

  /**
   * Check if the current workspace is a git repository
   */
  public async isGitRepository(workspacePath: string): Promise<boolean> {
    try {
      execSync("git rev-parse --git-dir", {
        cwd: workspacePath,
        stdio: "pipe",
      });
      return true;
    } catch {
      return false;
    }
  }

  /**
   * Get the git repository root path
   */
  public async getRepositoryRoot(
    workspacePath: string,
  ): Promise<string | null> {
    try {
      const result = execSync("git rev-parse --show-toplevel", {
        cwd: workspacePath,
        stdio: "pipe",
        encoding: "utf8",
      });
      return result.trim();
    } catch {
      return null;
    }
  }

  /**
   * Commit the learnings storage folder and push it to GitHub when auto-push is on.
   * The repository lives alongside the learnings data (customStorageLocation or
   * global storage), never in the currently open workspace.
   */
  public async syncLearningsToGit(learningsPath?: string): Promise<boolean> {
    this.lastError = undefined;

    if (!this.enableGitHubSync) {
      this.lastError =
        "GitHub sync is disabled (ai-learning-repo.enableGitHubSync).";
      return false;
    }

    try {
      const repoRoot = this.getLearningsRepoRoot();
      const setup = await this.ensureRepository(repoRoot);
      if (!setup.ok) {
        this.lastError = setup.error;
        console.log("[GitSync] Skipping sync: " + setup.error);
        return false;
      }

      if (learningsPath) {
        console.log(
          "[GitSync] Syncing storage repo " +
            repoRoot +
            " (trigger: " +
            learningsPath +
            ")",
        );
      }

      // Version the whole learnings storage folder; .gitignore keeps backups out.
      execSync('git add -A "."', { cwd: repoRoot, stdio: "pipe" });

      const hasChanges = await this.hasChanges(".", repoRoot);
      if (!hasChanges) {
        if (this.autoPush) {
          return this.pushToOrigin(repoRoot);
        }
        return false;
      }

      if (!this.autoCommit) {
        this.lastError =
          "Auto-commit is disabled (ai-learning-repo.gitHubAutoCommit).";
        return false;
      }

      const timestamp = new Date().toISOString();
      const commitMessage = "chore: sync learnings - " + timestamp;

      try {
        execSync('git commit -m "' + commitMessage + '"', {
          cwd: repoRoot,
          stdio: "pipe",
        });
        console.log("[GitSync] Committed: " + commitMessage);
      } catch (commitError) {
        this.lastError = "Commit failed: " + this.describeGitError(commitError);
        console.warn("[GitSync]", this.lastError);
        return false;
      }

      if (this.autoPush) {
        const pushed = await this.pushToOrigin(repoRoot);
        if (pushed) {
          vscode.window.showInformationMessage(
            "Learnings pushed to GitHub (" + this.gitHubRepoUrl + ")",
          );
        } else {
          vscode.window.showWarningMessage(
            "Learnings committed locally but push failed: " + this.lastError,
          );
        }
      } else {
        vscode.window.showInformationMessage("Learnings committed to Git");
      }

      return true;
    } catch (error) {
      this.lastError = this.describeGitError(error);
      console.warn("[GitSync] Git sync error:", this.lastError);
      return false;
    }
  }

  /**
   * Push the configured branch to origin. Credentials live in the remote URL so
   * pushes never block on an interactive prompt.
   */
  private async pushToOrigin(repoRoot: string): Promise<boolean> {
    try {
      execSync("git push -u origin " + this.syncBranch, {
        cwd: repoRoot,
        stdio: "pipe",
      });
      console.log("[GitSync] Pushed to origin/" + this.syncBranch);
      return true;
    } catch (pushError) {
      const detail = this.describeGitError(pushError);

      if (/non-fast-forward|fetch first|rejected/i.test(detail)) {
        try {
          execSync("git pull origin " + this.syncBranch + " --rebase", {
            cwd: repoRoot,
            stdio: "pipe",
          });
          execSync("git push -u origin " + this.syncBranch, {
            cwd: repoRoot,
            stdio: "pipe",
          });
          console.log("[GitSync] Recovered from rejected push");
          return true;
        } catch (retryError) {
          this.lastError = "Push rejected: " + this.describeGitError(retryError);
          console.warn("[GitSync]", this.lastError);
          return false;
        }
      }

      this.lastError = "Push failed: " + detail;
      console.warn("[GitSync]", this.lastError);
      return false;
    }
  }

  /**
   * Check if a file has uncommitted changes
   */
  private async hasChanges(
    filePath: string,
    repoRoot: string,
  ): Promise<boolean> {
    try {
      // Check both staged and unstaged changes
      const statusOutput = execSync(`git status --porcelain "${filePath}"`, {
        cwd: repoRoot,
        stdio: "pipe",
        encoding: "utf8",
      });

      return statusOutput.trim().length > 0;
    } catch {
      return false;
    }
  }

  /**
   * Pull latest changes from git
   */
  public async pullLatestLearnings(_unusedPath?: string): Promise<boolean> {
    this.lastError = undefined;

    if (!this.enableGitHubSync) {
      this.lastError =
        "GitHub sync is disabled (ai-learning-repo.enableGitHubSync).";
      return false;
    }

    const repoRoot = this.getLearningsRepoRoot();
    const setup = await this.ensureRepository(repoRoot);
    if (!setup.ok) {
      this.lastError = setup.error;
      console.log("[GitSync] Skipping pull: " + setup.error);
      return false;
    }

    try {
      execSync("git fetch origin", { cwd: repoRoot, stdio: "pipe" });
      execSync("git pull origin " + this.syncBranch + " --no-rebase", {
        cwd: repoRoot,
        stdio: "pipe",
      });

      console.log("[GitSync] Pulled latest learnings from Git");
      return true;
    } catch (error) {
      this.lastError = "Pull failed: " + this.describeGitError(error);
      console.warn("[GitSync]", this.lastError);
      return false;
    }
  }

  /**
   * Get secure storage reference
   */
  public getSecureStorage(): SecureStorageManager {
    return this.secureStorage;
  }

  /**
   * Setup private GitHub repository
   * Validates token, creates repo if needed, and configures git remote
   */
  public async setupPrivateGitHubRepository(token: string): Promise<{
    success: boolean;
    message: string;
    repoUrl?: string;
  }> {
    try {
      // Validate token
      const user = await this.gitHubAPI.validateToken(token);
      if (!user) {
        return {
          success: false,
          message:
            "Invalid GitHub token. Please check your personal access token.",
        };
      }

      console.log(`GitHub authentication successful for user: ${user.login}`);

      // Store token securely
      await this.secureStorage.setGitHubToken(token);

      // Check if repo URL is configured
      if (!this.gitHubRepoUrl || !this.gitHubRepoUrl.trim()) {
        // Auto-create if enabled
        const config = vscode.workspace.getConfiguration("ai-learning-repo");
        const autoCreate = config.get("gitHubAutoCreateRepo", false);

        if (autoCreate) {
          const description = config.get(
            "gitHubRepositoryDescription",
            "AI Learning Repository",
          );
          const repo = await this.gitHubAPI.createPrivateRepository(
            token,
            "ai-learnings",
            description,
          );

          if (repo) {
            // Update config with new repo URL
            await config.update(
              "gitHubRepoUrl",
              `https://github.com/${repo.owner}/${repo.repo}`,
              vscode.ConfigurationTarget.Global,
            );
            this.gitHubRepoUrl = `https://github.com/${repo.owner}/${repo.repo}`;

            return {
              success: true,
              message: `Private repository created successfully: ${repo.url}`,
              repoUrl: repo.url,
            };
          } else {
            return {
              success: false,
              message: "Failed to create private repository",
            };
          }
        }

        return {
          success: false,
          message:
            "No repository configured. Please set gitHubRepoUrl or enable auto-creation.",
        };
      }

      // Validate existing repo
      const parsed = this.gitHubAPI.parseRepositoryUrl(this.gitHubRepoUrl);
      if (!parsed) {
        return {
          success: false,
          message: "Invalid repository URL format",
        };
      }

      const hasAccess = await this.gitHubAPI.hasRepositoryAccess(
        parsed.owner,
        parsed.repo,
        token,
      );

      if (!hasAccess) {
        return {
          success: false,
          message: `No push access to repository: ${this.gitHubRepoUrl}`,
        };
      }

      // Point the learnings storage folder at the validated repository so the
      // next sync can push without any further setup.
      await this.ensureRepository(this.getLearningsRepoRoot());

      return {
        success: true,
        message: `Successfully authenticated with repository: ${this.gitHubRepoUrl}`,
        repoUrl: `https://github.com/${parsed.owner}/${parsed.repo}`,
      };
    } catch (error) {
      return {
        success: false,
        message: `Setup failed: ${error}`,
      };
    }
  }

  /**
   * Check private GitHub repo status
   */
  public async checkPrivateRepoStatus(): Promise<{
    configured: boolean;
    authenticated: boolean;
    hasAccess: boolean;
    repoUrl?: string;
  }> {
    const configured =
      !!this.gitHubRepoUrl && this.gitHubRepoUrl.trim().length > 0;
    const hasToken = await this.secureStorage.hasGitHubToken();

    if (!configured || !hasToken) {
      return {
        configured,
        authenticated: false,
        hasAccess: false,
      };
    }

    const token = await this.secureStorage.getGitHubToken();
    if (!token) {
      return {
        configured,
        authenticated: false,
        hasAccess: false,
      };
    }

    const parsed = this.gitHubAPI.parseRepositoryUrl(this.gitHubRepoUrl);
    if (!parsed) {
      return {
        configured,
        authenticated: false,
        hasAccess: false,
      };
    }

    const hasAccess = await this.gitHubAPI.hasRepositoryAccess(
      parsed.owner,
      parsed.repo,
      token,
    );

    return {
      configured,
      authenticated: true,
      hasAccess,
      repoUrl: this.gitHubRepoUrl,
    };
  }

  /**
   * Configure git remote for private repo
   */
  public async configurePrivateRepoRemote(
    workspacePath?: string,
  ): Promise<boolean> {
    const repoRoot = workspacePath || this.getLearningsRepoRoot();
    const result = await this.ensureRepository(repoRoot);
    if (!result.ok) {
      console.warn("[GitSync] Remote configuration failed:", result.error);
      return false;
    }
    console.log("Git remote configured for repository " + this.gitHubRepoUrl);
    return true;
  }

  /**
   * Get git status summary
   */
  public async getGitStatus(workspacePath?: string): Promise<{
    isGitRepo: boolean;
    branch?: string;
    hasChanges: boolean;
    stagedChanges: number;
    unstagedChanges: number;
    repoRoot?: string;
    remote?: string;
    repoUrl?: string;
  }> {
    const storageRoot = this.getLearningsRepoRoot();
    const isGitRepo = await this.isGitRepository(workspacePath || storageRoot);

    let remote = "";
    try {
      remote = execSync("git remote get-url origin", {
        cwd: storageRoot,
        stdio: "pipe",
        encoding: "utf8",
      }).trim();
    } catch {
      remote = "";
    }
    const safeRemote = remote.replace(/\/\/[^@/]+@/, "//***@");

    if (!isGitRepo) {
      return {
        isGitRepo: false,
        hasChanges: false,
        stagedChanges: 0,
        unstagedChanges: 0,
        repoRoot: storageRoot,
        remote: safeRemote,
        repoUrl: this.gitHubRepoUrl,
      };
    }

    try {
      const repoRoot = await this.getRepositoryRoot(storageRoot);
      if (!repoRoot) {
        return {
          isGitRepo: true,
          hasChanges: false,
          stagedChanges: 0,
          unstagedChanges: 0,
          repoRoot: storageRoot,
          remote: safeRemote,
          repoUrl: this.gitHubRepoUrl,
        };
      }

      // Get current branch
      const branchOutput = execSync("git rev-parse --abbrev-ref HEAD", {
        cwd: repoRoot,
        stdio: "pipe",
        encoding: "utf8",
      });
      const branch = branchOutput.trim();

      // Get status
      const statusOutput = execSync('git status --porcelain -- "."', {
        cwd: repoRoot,
        stdio: "pipe",
        encoding: "utf8",
      });

      const lines = statusOutput
        .trim()
        .split("\n")
        .filter((l) => l);
      const staged = lines.filter((l) => l.match(/^[MADRC]/)).length;
      const unstaged = lines.filter((l) => l.match(/^.[MADRC]/)).length;

      return {
        isGitRepo: true,
        branch,
        hasChanges: lines.length > 0,
        stagedChanges: staged,
        unstagedChanges: unstaged,
        repoRoot: storageRoot,
        remote: safeRemote,
        repoUrl: this.gitHubRepoUrl,
      };
    } catch {
      return {
        isGitRepo: true,
        hasChanges: false,
        stagedChanges: 0,
        unstagedChanges: 0,
        repoRoot: storageRoot,
        remote: safeRemote,
        repoUrl: this.gitHubRepoUrl,
      };
    }
  }
}
